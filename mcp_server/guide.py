GUIDE = """\
# 안테나 오케스트레이터 — 사용법

## 이 서버가 무엇인가

안테나 원천 파일(CST 프로젝트 · DXF/DWG 도면 · Gerber)을 읽어 **값을 뽑고, 그림을 그리고,
문서 골격을 만들고, 문서를 검사**한다. 서버는 **LLM 을 부르지 않는다** — 전부 결정론이다.

문서에서 **말을 쓰는 것은 당신(호스트 LLM)의 일**이고, 그 밖은 전부 서버가 한다.
이 경계 때문에 어떤 모델을 붙여도 산출물의 수치가 흔들리지 않는다.

## 절대 규칙 넷 — 어기면 게이트가 반려한다

1. **숫자를 타이핑하지 않는다.** 문서에 들어가는 모든 값은 `{{v:키}}` 같은 **참조**다.
   서버가 결정론으로 치환한다. 카탈로그에 없는 값은 문서에 쓸 수 없다 — 계산해서 만들 수도 없다.
2. **`|역할` 을 건드리지 않는다.** 골격이 `{{v:<키>|band_lo_ghz}}` 를 주면 `<키>` 만 바꾼다.
   역할은 골격(결정론)이 정하고 키는 당신이 고른다 — 두 진술이 어긋나면 키 오배치로 잡힌다.
3. **`PROSE` 마커 사이에만 쓴다.** 표·제목·주석·대장은 결정론 산출이다. 마커 밖을 한 글자라도
   고치면 `template_modified` 로 반려된다.
4. **행렬 표의 행을 건드리지 않는다.** 이미 키가 박혀 있는 칸은 템플릿의 일부다.
   9300 행에 9400 의 값을 넣으면 역할은 맞아도 뜻이 틀린다 — 그래서 아예 못 바꾸게 막아 두었다.

## 고르는 것은 사람이다 — 그림도 마찬가지다 (A-1)

같은 형상을 세 렌더러가 각각 그린다. 래스터 300dpi · 벡터 SVG · 오프라인 3D 뷰.
**무엇이 나은지는 데이터에 없다** — 무엇에 쓰느냐의 문제라 도구가 정할 수 없다.

`figure_variants(run_id)` 의 `n_variants` 가 2 이상이면 **반드시**:

1. 후보를 사용자에게 **보여준다.** `path` 가 실제 파일 자리다. 셋의 차이(축척이 실리는가 ·
   확대해도 안 깨지는가 · 돌려 볼 수 있는가)를 한 줄씩 붙여 준다.
2. 사용자가 고르면 `figure_choose(run_id, variant, by="<사용자>")` 에 넣는다.
3. `run_pipeline` 을 다시 돌린다 — 그래야 고른 것이 문서에 실린다.

**묻지 않고 고르지 않는다.** 고를 때까지는 기본값(`raster`)이 서고, 대장에
"아직 안 골랐다"가 뜬다 — 문서는 막히지 않는다. 선택은 **제품 단위**로 남으므로
같은 제품의 다음 run 부터는 묻지 않는다.

## 그래서 당신이 하는 일

`document_brief(run_id)` 를 부르면 세 가지가 온다.

- **골격** — 절 구성이 이미 다 서 있고, 값 자리는 `<키>` 로 비어 있다.
- **카탈로그** — 쓸 수 있는 값의 **전부**. 각 항목에 키 · 값 · 역할 · 산지가 있다.
- **서술 지침** — 각 `PROSE` 슬롯에 무엇을 쓸지.

당신은 ① `<키>` 를 카탈로그의 키로 바꾸고 ② 마커 사이에 소견을 쓴다. 그게 전부다.
다 쓰면 `submit_document(run_id, markdown)` 에 넣는다. 통과하면 치환본이 나오고,
안 되면 **무엇을 어디서 어겼는지** 목록이 온다 — 그것만 고쳐 다시 낸다.

## 서술을 쓸 때

- 숫자를 쓰지 않는다. 값이 필요하면 그 값은 이미 위 표에 있다 — 표를 가리키는 말로 쓴다.
- 표에 있는 것을 되풀이하지 않는다. **표가 말하지 못하는 것**(왜 · 무엇을 뜻하는지 · 무엇이
  빈지)을 쓴다.
- 확인되지 않은 것을 단정하지 않는다. 근거가 없으면 "확인되지 않았다"고 쓴다.
- 시뮬레이션값과 측정값을 같은 말로 부르지 않는다. 어느 레인인지는 절 제목이 정해 두었다.
- 계산값을 성능이라고 부르지 않는다. 배열인자는 빔패턴이 아니다(소자 패턴이 없다).

## 값이 없을 때

문서 마지막에 **업데이트 필요 대장**이 선다. 공백은 세 종류다.

| 종류 | 뜻 | 당신이 할 일 |
| --- | --- | --- |
| **선언** | 아는 사람이 말하면 그만 | 사용자에게 **물어본다.** 답을 들으면 `declare_set` 에 넣는다 |
| 반입 | 파일이 들어와야 한다 | 무엇이 필요한지 알린다. 말로는 못 채운다 |
| 도구 | 도구가 아직 못 읽는다 | 무엇이 갖춰져야 하는지 알린다 |

`declare_gaps(run_id)` 가 지금 물으면 되는 것을 목록으로 준다.
★ 사용자가 알려준 값을 **문서에 직접 적지 않는다.** `declare_set` 으로 넣고 파이프라인을
다시 돌린다 — 그래야 값이 출처와 함께 실린다.

## 하지 않는 것

- 판독 못 하는 포맷에 파서를 만들지 않는다. "판독 불가 + 사유"로 남기고 넘어간다.
- 없는 경계를 지어내지 않는다. 가를 수 없으면 **묻는다**.
- 확정하지 않는다. 도구는 제안하고 사람이 정한다.
- 원본을 고치지 않는다. 쓰기는 작업 폴더 · 산출 폴더 · 원장 · 선언 파일뿐이다.

## 표준 순서

    orch_status()                      지금 환경이 성립하는가 · 원장 정본이 하나인가
    discover_sources(경로)              폴더 안에 안테나가 몇 개인가
    run_pipeline(경로, product=...)     식별 → 추출 → 해석 → 렌더 → 카탈로그 → 골격
    run_report(run_id)                 무엇이 나왔나 · 무엇이 비었나
    document_brief(run_id)             ← 여기서부터 당신 차례
    submit_document(run_id, md)        게이트 통과까지 되풀이
    declare_gaps / declare_set         빈 것 중 말로 채울 수 있는 것

분석이 더 필요하면 `compare_revisions`(판본) · `crosscheck`(교차 검증) ·
`relate_entries`(자산 사이 관계) · `asset_query`(자산 DB) · `ledger_events`(실행 기록).
"""

